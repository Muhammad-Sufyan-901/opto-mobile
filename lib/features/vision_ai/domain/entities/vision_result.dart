/// Sealed domain result hierarchy for all Vision AI analyses.
///
/// Each [VisionMode] produces exactly one concrete subtype when the
/// analysis completes successfully. All subtypes are immutable value
/// objects — no `freezed` annotation needed since these are simple
/// final classes without serialisation requirements.
sealed class VisionResult {
  const VisionResult();
}

// ---------------------------------------------------------------------------
// OCR  (VisionMode.readText)
// ---------------------------------------------------------------------------

/// Result of on-device ML Kit text recognition (OCR).
///
/// [text] is the concatenated string of all recognised text blocks.
/// [blocks] retains the individual block strings for future line-break
/// or spatial-positioning use-cases.
final class OcrResult extends VisionResult {
  const OcrResult({required this.text, required this.blocks});

  /// Full recognised text string, bilingual (BI + EN).
  final String text;

  /// Individual text blocks (one per line or paragraph).
  final List<String> blocks;

  /// Builds a spoken summary for [AuraTts] and live-region updates.
  ///
  /// Returns the full [text] if non-empty; otherwise a bilingual
  /// "no text found" message.
  String toSpokenString() =>
      text.isNotEmpty ? text : 'Tidak ada teks ditemukan. No text found.';

  @override
  String toString() => 'OcrResult(${blocks.length} blocks)';
}

// ---------------------------------------------------------------------------
// Object detection  (VisionMode.identify)
// ---------------------------------------------------------------------------

/// Result of on-device ML Kit object detection.
///
/// [labels] are sorted by confidence (highest first) and localised to
/// both English and Bahasa Indonesia where the ML Kit model provides it.
final class ObjectResult extends VisionResult {
  const ObjectResult({required this.labels});

  /// Detected object labels, highest-confidence first.
  final List<String> labels;

  /// Spoken summary — lists the top-3 labels or announces "nothing found".
  String toSpokenString() {
    if (labels.isEmpty) {
      return 'Tidak ada objek terdeteksi. No objects identified.';
    }
    final top = labels.take(3).join(', ');
    return 'Terdeteksi: $top.';
  }

  @override
  String toString() => 'ObjectResult(${labels.length} labels)';
}

// ---------------------------------------------------------------------------
// Color detection  (VisionMode.colors)
// ---------------------------------------------------------------------------

/// Result of on-device dominant-color pixel analysis.
///
/// [dominantColors] contains up to 3 bilingual color names
/// (e.g. "Blue / Biru"), most-dominant first.
final class ColorResult extends VisionResult {
  const ColorResult({required this.dominantColors});

  /// Up to 3 color names, most-dominant first.
  final List<String> dominantColors;

  /// Spoken summary.
  String toSpokenString() {
    if (dominantColors.isEmpty) {
      return 'Warna tidak terdeteksi. No dominant color found.';
    }
    return 'Warna dominan: ${dominantColors.join(', ')}.';
  }

  @override
  String toString() => 'ColorResult($dominantColors)';
}

// ---------------------------------------------------------------------------
// Scene description  (VisionMode.describeScene)
// ---------------------------------------------------------------------------

/// Whether the scene result came from the cloud or an offline/quota fallback.
enum SceneResultSource {
  /// Description generated by the `scene-describe` Edge Function
  /// (Google Gemini 2.5 Flash-Lite).
  /// Output is a concise Bahasa Indonesia caption (1–2 sentences).
  cloud,

  /// Cloud unavailable (offline, timeout, or Gemini server error); description
  /// was assembled from on-device ML Kit object-detection labels as a fallback.
  offlineFallback,

  /// Gemini daily/per-minute quota was exhausted (HTTP 429). The on-device
  /// fallback is returned alongside this source so the UI can surface a
  /// distinct spoken message ("Batas harian deskripsi tercapai — coba lagi
  /// besok. OCR masih berfungsi.") rather than the generic offline notice.
  quotaExhausted,
}

/// Result of scene description (cloud or offline fallback).
final class SceneResult extends VisionResult {
  const SceneResult({
    required this.description,
    required this.source,
  });

  /// Natural-language description of the scene.
  final String description;

  /// Whether this result came from the cloud LLM or the local fallback.
  final SceneResultSource source;

  bool get isOfflineFallback =>
      source == SceneResultSource.offlineFallback;

  bool get isQuotaExhausted =>
      source == SceneResultSource.quotaExhausted;

  /// Spoken summary:
  /// - [SceneResultSource.cloud]: returns the Bahasa Indonesia caption as-is.
  /// - [SceneResultSource.offlineFallback]: returns [description] which already
  ///   contains the bilingual degradation notice from [VisionRepositoryImpl].
  /// - [SceneResultSource.quotaExhausted]: returns a distinct BI message so
  ///   users know the quota is the cause, not a network issue.
  ///   Never silent — the UI must always speak a result (design_system.md §12.2).
  String toSpokenString() {
    if (isQuotaExhausted) {
      return 'Batas harian deskripsi tercapai — coba lagi besok. '
          'OCR masih berfungsi.';
    }
    // For cloud and offlineFallback, description already contains the right text.
    return description;
  }

  @override
  String toString() {
    final preview = description.length > 40
        ? '${description.substring(0, 40)}…'
        : description;
    return 'SceneResult(source: $source, "$preview")';
  }
}
